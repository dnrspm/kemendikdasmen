// Calculate workload metrics
export function calculateWorkloadMetrics(tasks: Task[]) {
  const total = tasks.length;
  const inProgress = tasks.filter(t => t.status === 'sedang_dikerjakan').length;
  const completed = tasks.filter(t => t.status === 'selesai').length;
  const overdue = tasks.filter(t => {
    const dueDate = new Date(t.due_date);
    const today = new Date();
    return t.status !== 'selesai' && dueDate < today;
  }).length;
  const completionRate = total > 0 ? Math.round((completed / total) * 100) : 0;

  return {
    total,
    inProgress,
    completed,
    overdue,
    completionRate
  };
}