export interface Task {
  id: string;
  title: string;
  description: string;
  epic_id: string | null;
  epic_name?: string; // SKP/Output tujuan
  team_id: string;
  biro_id?: string; // Biro assignment
  tim_kerja_id?: string; // Tim Kerja assignment
  status: TaskStatus;
  assignee_id: string;
  assignee_name: string; // Pelaku Tugas
  assignee_avatar?: string;
  assignees?: Array<{ // Multiple assignees support
    id: string;
    name: string;
    avatar?: string;
  }>;
  reporter_id: string;
  reporter_name: string; // Pemberi Tugas
  priority: TaskPriority;
  program_priority?: ProgramPriority; // Inherit dari Epic
  labels: string[];
  story_points?: number;
  due_date: string; // Batas Waktu
  start_date?: string;
  completed_date?: string;
  time_spent?: number;
  bukti_dukung_url?: string;
  created_at: string;
  updated_at: string;
}

export interface Epic {
  id: string;
  name: string;
  description: string;
  sasaran_kinerja_id?: string; // Terkait Sasaran Kinerja
  sasaran_kinerja_name?: string;
  owner_org_id: string;
  owner_org_name: string;
  biro_id?: string; // Which biro owns this epic
  biro_name?: string;
  tim_kerja_id?: string;
  tim_kerja_name?: string;
  pic_name?: string;
  status: EpicStatus;
  priority: TaskPriority;
  program_priority?: ProgramPriority; // Label prioritas program
  rhk_id?: string; // Terkait RHK mana
  rhk_name?: string;
  start_date: string;
  due_date: string;
  completed_date?: string;
  progress: number;
  created_by: string;
  created_at: string;
  updated_at: string;
}

export interface Comment {
  id: string;
  task_id: string;
  user_id: string;
  user_name: string;
  user_avatar?: string;
  content: string;
  created_at: string;
}

